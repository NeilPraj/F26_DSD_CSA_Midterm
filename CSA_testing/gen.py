#!/usr/bin/env python3
"""
Generate a Monte Carlo testbench for carry_select_16.

Hand-writing the alter lines doesn't scale: the 16-bit adder has
32 full adders (each 2x xor2x1 + 1x mux2x1) plus 21 select muxes,
which is 1276 transistors and 2552 alter lines. This script writes
them for you, using the same agauss/alter loop as your full adder
and mux testbenches.

Usage:  python3 gen_mc.py   ->  writes carry_select_mc.sp
"""

HEX = "0123456789abcdef"  # ngspice lowercases names, so xfaA_0 becomes xfaa_0

# Transistor names inside each leaf cell (must match cell_lib.sp)
FETS = {
    "xor": [f"m{i}" for i in range(10)],
    "mux": ["mo0", "mo1"] + [f"m{i}" for i in range(10)],
}

# Every leaf gate in the design: (hierarchical path, cell type)
gates = []
for bit in HEX:
    for copy in "01":  # _0 = assumes carry-in 0, _1 = assumes carry-in 1
        fa = f"xdut.xfa{bit}_{copy}"
        gates += [
            (f"{fa}.xxor1", "xor"),
            (f"{fa}.xxor2", "xor"),
            (f"{fa}.xmux1", "mux"),
        ]
for bit in HEX:  # sum-select muxes
    gates.append((f"xdut.xmux_s{bit}", "mux"))
for c in ["c2", "c5", "c9", "ce", "cout"]:  # carry-select muxes
    gates.append((f"xdut.xmux_{c}", "mux"))

# Every copy of a cell has the same nominal W/L, so read each value once
# from a reference instance before the loop starts altering anything.
REF = {"xor": "xdut.xfa0_0.xxor1", "mux": "xdut.xfa0_0.xmux1"}

nominals = []
for cell, ref in REF.items():
    for fet in FETS[cell]:
        for p in "wl":
            nominals.append(f"let {cell}_{fet}{p} = @m.{ref}.{fet}[{p}]")

alters = []
for path, cell in gates:
    for fet in FETS[cell]:
        for p in "wl":
            alters.append(
                f"  alter @m.{path}.{fet}[{p}] = agauss({cell}_{fet}{p}, 18n, 3)"
            )

TEMPLATE = """* carry_select_16 Monte Carlo testbench
* GENERATED by gen_mc.py -- edit the script, not this file.
.include ../cell_lib.sp

.global vdd
.global vss
Vdd vdd 0 dc 3.3v
Vss vss 0 dc 0

* Worst case: A = 0xFFFF, CIN = 0, B toggles 0x0000 <-> 0x0001 (only B0 switches)
* B=0x0000 -> S=0xFFFF, COUT=0
* B=0x0001 -> S=0x0000, COUT=1
* The carry generated at bit 0 ripples through stage 1's full adders (fa0_0 -> fa1_0),
* then through every carry-select mux (c2 -> c5 -> c9 -> cE -> cout). Toggling CIN instead
* would skip the stage-1 ripple, since CIN drives the first mux select directly.
xdut @@A@@ b0 @@B@@ cin @@S@@ cout carry_select_16
@@CAPS@@
Ccout cout vss 10f
Vcin cin 0 dc 0
Vb0  b0  0 PULSE(0v 3.3v 50n 1n 1n 49n 100n)

.control
let mc_runs = 100
let current_run = 0
set curplot = new
set tran_meas = $curplot
let tplh_cout = vector(mc_runs)
let tphl_cout = vector(mc_runs)
let tplh_sf   = vector(mc_runs)
let tphl_sf   = vector(mc_runs)

define agauss(nom, avar, sig) (nom + avar/sig * sgauss(0))

* nominal sizes, read once from reference instances
@@NOMINALS@@

dowhile current_run < mc_runs
@@ALTERS@@

  tran 10p 150n 40n
  meas tran d_lh_cout TRIG v(b0) val=1.65 rise=1 TARG v(cout) val=1.65 rise=1
  meas tran d_hl_cout TRIG v(b0) val=1.65 fall=1 TARG v(cout) val=1.65 fall=1
  meas tran d_hl_sf   TRIG v(b0) val=1.65 rise=1 TARG v(sf)   val=1.65 fall=1
  meas tran d_lh_sf   TRIG v(b0) val=1.65 fall=1 TARG v(sf)   val=1.65 rise=1

  set simplot = $curplot
  setplot $tran_meas

  let tplh_cout[current_run] = {$simplot}.d_lh_cout
  let tphl_cout[current_run] = {$simplot}.d_hl_cout
  let tplh_sf[current_run]   = {$simplot}.d_lh_sf
  let tphl_sf[current_run]   = {$simplot}.d_hl_sf

  destroy $simplot
  let current_run = current_run + 1
end

print tplh_cout tphl_cout tplh_sf tphl_sf

set wr_singlescale
set wr_vecnames
wrdata carry_select_mc.txt tplh_cout tphl_cout tplh_sf tphl_sf
quit
.endc
.end
"""

out = (
    TEMPLATE.replace("@@A@@", " ".join(["vdd"] * 16))
    .replace("@@B@@", " ".join(["vss"] * 15))  # b1..bF; b0 is driven by Vb0
    .replace("@@S@@", " ".join(f"s{b}" for b in HEX))
    .replace("@@CAPS@@", "\n".join(f"Cs{b} s{b} vss 10f" for b in HEX))
    .replace("@@NOMINALS@@", "\n".join(nominals))
    .replace("@@ALTERS@@", "\n".join(alters))
)

with open("carry_select_mc.sp", "w") as f:
    f.write(out)

n_fets = sum(len(FETS[c]) for _, c in gates)
print(f"{len(gates)} gates, {n_fets} transistors, {len(alters)} alter lines")
print("wrote carry_select_mc.sp")
